let currentLanguage = localStorage.getItem(LANGUAGE_STORAGE_KEY);
if (!SUPPORTED_LANGUAGES.includes(currentLanguage)) currentLanguage = "vi";

function translate(key, values = {}) {
  let result = TRANSLATIONS[currentLanguage]?.[key] ?? key;
  for (const [name, value] of Object.entries(values)) {
    result = result.replaceAll(`{${name}}`, String(value));
  }
  return result;
}

function applyLanguage(language, persist = true) {
  if (!SUPPORTED_LANGUAGES.includes(language)) return;
  currentLanguage = language;
  if (persist) localStorage.setItem(LANGUAGE_STORAGE_KEY, language);
  document.documentElement.lang = language;
  document.title = `Label Studio — ${translate("Label designer")}`;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = translate(element.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-title]").forEach((element) => {
    element.title = translate(element.dataset.i18nTitle);
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
    element.setAttribute("aria-label", translate(element.dataset.i18nAria));
  });
  document.querySelector("#language-select").value = language;
}
